template<class... Args> inline std::string Format(const char* format, Args... args)
{
    const auto localized = Translate(format ? format : "");
    if constexpr (sizeof...(args) == 0)
    {
        // A dynamic string is data, never an uncontrolled printf format.
        auto text = localized;
        size_t pos = 0;
        while ((pos = text.find("%%", pos)) != std::string::npos) { text.erase(pos, 1); ++pos; }
        return text;
    }
    auto storage = std::make_tuple(Argument(args)...);
    return std::apply([&](const auto&... values)
    {
        const int count = std::snprintf(nullptr, 0, localized.c_str(), PrintArgument(values)...);
        if (count < 0) return localized;
        std::string output(static_cast<size_t>(count) + 1, '\0');
        std::snprintf(output.data(), output.size(), localized.c_str(), PrintArgument(values)...);
        output.resize(static_cast<size_t>(count));
        return Translate(output);
    }, storage);
}

