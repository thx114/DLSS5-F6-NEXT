inline const std::unordered_map<std::string, std::string>& EnglishDictionary()
{ static const std::unordered_map<std::string, std::string> value(std::begin(Dictionary), std::end(Dictionary)); return value; }
inline const std::unordered_map<std::string, std::string>& ChineseDictionary()
{
    static const auto value = [] { std::unordered_map<std::string, std::string> result;
        for (const auto& entry : Dictionary) result.try_emplace(entry.second, entry.first); return result; }();
    return value;
}
struct FragmentNode { std::unordered_map<unsigned char, size_t> next; const char* translation = nullptr; };
inline const std::vector<FragmentNode>& ChineseFragments()
{
    static const auto value = [] { std::vector<FragmentNode> result(1);
        for (const auto& entry : Dictionary) if (std::string_view(entry.first).find('%') == std::string_view::npos &&
            std::string_view(entry.first).find("{}") == std::string_view::npos)
        {
            size_t node = 0;
            for (const auto byte : std::string_view(entry.first))
            {
                const auto key = static_cast<unsigned char>(byte);
                auto found = result[node].next.find(key);
                if (found == result[node].next.end())
                { const size_t index = result.size(); result[node].next.emplace(key, index); result.emplace_back(); node = index; }
                else node = found->second;
            }
            result[node].translation = entry.second;
        }
        return result; }();
    return value;
}
// Generated dictionary above; runtime below is intentionally independent of Config/GPU code.
inline std::string Translate(std::string_view source)
{
    const bool english = NextgenUi::English();
    const auto& map = english ? EnglishDictionary() : ChineseDictionary();
    if (auto found = map.find(std::string(source)); found != map.end()) return found->second;
    // Paths and file names are user data. Preserve their spelling and percent signs.
    if (source.find('\\') != std::string_view::npos || source.find(":/") != std::string_view::npos ||
        source.find("://") != std::string_view::npos || source.starts_with('/') ||
        source.starts_with("./") || source.starts_with("../") || source.ends_with(".cube") ||
        source.ends_with(".dll") || source.ends_with(".ini") || source.ends_with(".log")) return std::string(source);
    const auto marker = source.find("##");
    if (marker != std::string_view::npos)
    {
        auto visible = source.substr(0, marker);
        if (auto found = map.find(std::string(visible)); found != map.end())
            return found->second + std::string(source.substr(marker));
    }
    // Dynamic Chinese strings are composed from the same UI-only literal fragments.
    // Never rewrite English substrings: runtime names, paths and technical tokens stay exact.
    if (english && std::any_of(source.begin(), source.end(), [](unsigned char c) { return c >= 0x80; }))
    {
        const auto& trie = ChineseFragments();
        std::string result;
        for (size_t pos = 0; pos < source.size();)
        {
            size_t node = 0, end = pos; const char* replacement = nullptr;
            for (size_t scan = pos; scan < source.size(); ++scan)
            {
                const auto found = trie[node].next.find(static_cast<unsigned char>(source[scan]));
                if (found == trie[node].next.end()) break;
                node = found->second;
                if (trie[node].translation) { replacement = trie[node].translation; end = scan + 1; }
            }
            if (replacement) { result += replacement; pos = end; }
            else result += source[pos++];
        }
        return result;
    }
    return std::string(source);
}

inline std::string StableLabel(const char* source)
{
    const std::string original = source ? source : "";
    const auto translated = Translate(original);
    // Explicit identities already carry their original ID seed. Never append a
    // second reset suffix containing the newly displayed title.
    if (const auto identity = original.find("###"); identity != std::string::npos)
        return translated.substr(0, translated.find("##")) + original.substr(identity);
    const auto sourceMarker = original.find("##");
    const auto sourceVisible = original.substr(0, sourceMarker);
    const auto hasEntry = [](const std::unordered_map<std::string, std::string>& map, std::string_view value)
    { return map.find(std::string(value)) != map.end(); };
    const bool knownLabel = hasEntry(EnglishDictionary(), original) || hasEntry(ChineseDictionary(), original) ||
        (!sourceVisible.empty() && (hasEntry(EnglishDictionary(), sourceVisible) || hasEntry(ChineseDictionary(), sourceVisible)));
    if ((!knownLabel && translated == original) || original.starts_with("##")) return original;
    const auto visibleEnd = translated.find("##");
    // ImGui's ### resets the hash to the original label with the current ID seed.
    // This also preserves existing ## suffixes and dynamic IDs assembled by callers.
    return translated.substr(0, visibleEnd) + "###" + original;
}

