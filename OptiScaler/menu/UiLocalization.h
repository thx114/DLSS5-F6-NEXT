inline bool Combo(const char* label, int* selected, const char* const items[], int count, int height = -1)
{
    const char* preview = *selected >= 0 && *selected < count ? items[*selected] : "";
    if (height > 0) ImGui::SetNextWindowSizeConstraints(ImVec2(0, 0), ImVec2(FLT_MAX,
        ImGui::GetTextLineHeightWithSpacing() * height + ImGui::GetStyle().WindowPadding.y * 2));
    if (!BeginCombo(label, preview)) return false;
    bool changed = false;
    for (int i = 0; i < count; ++i)
    {
        ImGui::PushID(i);
        if (Selectable(items[i], i == *selected)) { *selected = i; changed = true; }
        if (i == *selected) ImGui::SetItemDefaultFocus();
        ImGui::PopID();
    }
    ImGui::EndCombo();
    return changed;
}
inline bool Segmented(const char* label,int* selected,const char* const items[],int count,
                       const bool* enabled=nullptr,const bool* visible=nullptr,
                       const char* const tips[]=nullptr)
{
    const auto stable=StableLabel(label);
    std::vector<std::string> labels;labels.reserve(count);
    std::vector<const char*> pointers;pointers.reserve(count);
    for(int i=0;i<count;++i)labels.push_back(StableLabel(items[i]));
    for(const auto& item:labels)pointers.push_back(item.c_str());
    // Per-option explanations travel with the option; translate them like the labels.
    std::vector<std::string> tipTexts;
    std::vector<const char*> tipPointers;
    if(tips){tipTexts.reserve(count);tipPointers.reserve(count);
        for(int i=0;i<count;++i){tipTexts.push_back(tips[i]?Translate(tips[i]):std::string());
            tipPointers.push_back(tipTexts.back().empty()?nullptr:tipTexts.back().c_str());}
    }
    return NextgenChoiceStyle::Segmented(stable.c_str(),selected,pointers.data(),count,enabled,visible,
                                          tips?tipPointers.data():nullptr);
}
