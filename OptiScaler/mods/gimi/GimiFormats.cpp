std::uint32_t FormatElementBytes(DXGI_FORMAT f) noexcept
{
    switch (f)
    {
    case DXGI_FORMAT_R32G32B32A32_FLOAT: case DXGI_FORMAT_R32G32B32A32_UINT: case DXGI_FORMAT_R32G32B32A32_SINT: return 16;
    case DXGI_FORMAT_R32G32B32_FLOAT: case DXGI_FORMAT_R32G32B32_UINT: case DXGI_FORMAT_R32G32B32_SINT: return 12;
    case DXGI_FORMAT_R16G16B16A16_FLOAT: case DXGI_FORMAT_R16G16B16A16_UNORM: case DXGI_FORMAT_R16G16B16A16_UINT:
    case DXGI_FORMAT_R16G16B16A16_SNORM: case DXGI_FORMAT_R16G16B16A16_SINT:
    case DXGI_FORMAT_R32G32_FLOAT: case DXGI_FORMAT_R32G32_UINT: case DXGI_FORMAT_R32G32_SINT: return 8;
    case DXGI_FORMAT_R8G8B8A8_UNORM: case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB: case DXGI_FORMAT_R8G8B8A8_UINT:
    case DXGI_FORMAT_R8G8B8A8_SNORM: case DXGI_FORMAT_R8G8B8A8_SINT:
    case DXGI_FORMAT_B8G8R8A8_UNORM: case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:
    case DXGI_FORMAT_R10G10B10A2_UNORM: case DXGI_FORMAT_R10G10B10A2_UINT: case DXGI_FORMAT_R11G11B10_FLOAT:
    case DXGI_FORMAT_R16G16_FLOAT: case DXGI_FORMAT_R16G16_UNORM: case DXGI_FORMAT_R16G16_UINT:
    case DXGI_FORMAT_R16G16_SNORM: case DXGI_FORMAT_R16G16_SINT:
    case DXGI_FORMAT_R32_FLOAT: case DXGI_FORMAT_R32_UINT: case DXGI_FORMAT_R32_SINT: return 4;
    case DXGI_FORMAT_R8G8_UNORM: case DXGI_FORMAT_R8G8_UINT: case DXGI_FORMAT_R8G8_SNORM: case DXGI_FORMAT_R8G8_SINT:
    case DXGI_FORMAT_R16_FLOAT: case DXGI_FORMAT_R16_UNORM: case DXGI_FORMAT_R16_UINT: case DXGI_FORMAT_R16_SNORM: case DXGI_FORMAT_R16_SINT: return 2;
    case DXGI_FORMAT_R8_UNORM: case DXGI_FORMAT_R8_UINT: case DXGI_FORMAT_R8_SNORM: case DXGI_FORMAT_R8_SINT: case DXGI_FORMAT_A8_UNORM: return 1;
    default: return 0;
    }
}
static unsigned BlockBytes(DXGI_FORMAT f) noexcept
{
    switch (f)
    {
    case DXGI_FORMAT_BC1_UNORM: case DXGI_FORMAT_BC1_UNORM_SRGB: case DXGI_FORMAT_BC4_UNORM: case DXGI_FORMAT_BC4_SNORM: return 8;
    case DXGI_FORMAT_BC2_UNORM: case DXGI_FORMAT_BC2_UNORM_SRGB: case DXGI_FORMAT_BC3_UNORM: case DXGI_FORMAT_BC3_UNORM_SRGB:
    case DXGI_FORMAT_BC5_UNORM: case DXGI_FORMAT_BC5_SNORM: case DXGI_FORMAT_BC6H_UF16: case DXGI_FORMAT_BC6H_SF16:
    case DXGI_FORMAT_BC7_UNORM: case DXGI_FORMAT_BC7_UNORM_SRGB: return 16;
    default: return 0;
    }
}
bool SupportedTextureFormat(DXGI_FORMAT f) noexcept { return FormatElementBytes(f) || BlockBytes(f); }
bool FormatSurface(DXGI_FORMAT f, std::uint32_t w, std::uint32_t h, SurfaceLayout& out) noexcept
{
    out = {};
    if (!w || !h) return false;
    const auto block = BlockBytes(f), pixel = FormatElementBytes(f);
    if (!block && !pixel) return false;
    const std::uint64_t row = block ? ((std::uint64_t(w) + 3) / 4) * block : std::uint64_t(w) * pixel;
    const std::uint64_t rows = block ? (std::uint64_t(h) + 3) / 4 : h;
    if (row > UINT32_MAX || rows > UINT32_MAX) return false;
    out = {static_cast<std::uint32_t>(row), static_cast<std::uint32_t>(rows), row * rows};
    return true;
}
DXGI_FORMAT ParseResourceFormat(std::string_view input)
{
    auto name = LowerAscii(Trim(input));
    if (name.compare(0, 12, "dxgi_format_") == 0) name.erase(0, 12);
    // Name spelling is folded below; table keeps SDK values out of the parser.
    struct Named { const char* name; DXGI_FORMAT format; };
#define GIMI_FORMAT(x) {#x, DXGI_FORMAT_##x}
    static const Named names[] = {
        GIMI_FORMAT(R32G32B32A32_FLOAT), GIMI_FORMAT(R32G32B32A32_UINT), GIMI_FORMAT(R32G32B32A32_SINT),
        GIMI_FORMAT(R32G32B32_FLOAT), GIMI_FORMAT(R32G32B32_UINT), GIMI_FORMAT(R32G32B32_SINT),
        GIMI_FORMAT(R32G32_FLOAT), GIMI_FORMAT(R32G32_UINT), GIMI_FORMAT(R32G32_SINT),
        GIMI_FORMAT(R16G16B16A16_FLOAT), GIMI_FORMAT(R16G16B16A16_UNORM), GIMI_FORMAT(R16G16B16A16_SNORM), GIMI_FORMAT(R16G16B16A16_UINT), GIMI_FORMAT(R16G16B16A16_SINT),
        GIMI_FORMAT(R8G8B8A8_UNORM), GIMI_FORMAT(R8G8B8A8_UNORM_SRGB), GIMI_FORMAT(R8G8B8A8_UINT), GIMI_FORMAT(R8G8B8A8_SNORM), GIMI_FORMAT(R8G8B8A8_SINT),
        GIMI_FORMAT(B8G8R8A8_UNORM), GIMI_FORMAT(B8G8R8A8_UNORM_SRGB), GIMI_FORMAT(R10G10B10A2_UNORM), GIMI_FORMAT(R10G10B10A2_UINT), GIMI_FORMAT(R11G11B10_FLOAT),
        GIMI_FORMAT(R16G16_FLOAT), GIMI_FORMAT(R16G16_UNORM), GIMI_FORMAT(R16G16_UINT), GIMI_FORMAT(R16G16_SNORM), GIMI_FORMAT(R16G16_SINT),
        GIMI_FORMAT(R32_FLOAT), GIMI_FORMAT(R32_UINT), GIMI_FORMAT(R32_SINT),
        GIMI_FORMAT(R8G8_UNORM), GIMI_FORMAT(R8G8_UINT), GIMI_FORMAT(R8G8_SNORM), GIMI_FORMAT(R8G8_SINT),
        GIMI_FORMAT(R16_FLOAT), GIMI_FORMAT(R16_UNORM), GIMI_FORMAT(R16_UINT), GIMI_FORMAT(R16_SNORM), GIMI_FORMAT(R16_SINT),
        GIMI_FORMAT(R8_UNORM), GIMI_FORMAT(R8_UINT), GIMI_FORMAT(R8_SNORM), GIMI_FORMAT(R8_SINT), GIMI_FORMAT(A8_UNORM),
        GIMI_FORMAT(BC1_UNORM), GIMI_FORMAT(BC1_UNORM_SRGB), GIMI_FORMAT(BC2_UNORM), GIMI_FORMAT(BC2_UNORM_SRGB),
        GIMI_FORMAT(BC3_UNORM), GIMI_FORMAT(BC3_UNORM_SRGB), GIMI_FORMAT(BC4_UNORM), GIMI_FORMAT(BC4_SNORM),
        GIMI_FORMAT(BC5_UNORM), GIMI_FORMAT(BC5_SNORM), GIMI_FORMAT(BC6H_UF16), GIMI_FORMAT(BC6H_SF16), GIMI_FORMAT(BC7_UNORM), GIMI_FORMAT(BC7_UNORM_SRGB)
    };
#undef GIMI_FORMAT
    for (const auto& entry : names) if (name == LowerAscii(entry.name)) return entry.format;
    return DXGI_FORMAT_UNKNOWN;
}
