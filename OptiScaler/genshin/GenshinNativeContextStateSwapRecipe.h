template<class Observation> inline bool StateSwapOwnedCodeRange(const detail::Image& image,uint32_t rva,
    const unsigned char* bytes,size_t size,Observation& o)noexcept {
    o.At("StateSwapOwnedCodeRange",rva);
    if(!o.Leaf("owned-code-section",image.SectionHas(rva,size,IMAGE_SCN_MEM_READ|IMAGE_SCN_MEM_EXECUTE,
        IMAGE_SCN_MEM_WRITE|IMAGE_SCN_MEM_DISCARDABLE)))return false;
    if(!o.Leaf("owned-code-clean-bytes",std::memcmp(image.clean.data()+rva,bytes,size)==0))return false;
    const auto* live=reinterpret_cast<const unsigned char*>(image.live)+rva;
    const auto* patch=detail::Find(live);
    if(!patch)return detail::Equal(live,bytes,size,o);
    if(!o.Leaf("owned-patch-image",patch->image==0))return false;
    if(!o.Leaf("owned-patch-rva",patch->rva==rva))return false;
    if(!o.Leaf("owned-patch-straight",patch->straight))return false;
    if(!o.Leaf("owned-patch-size-nonzero",patch->size!=0))return false;
    if(!o.Leaf("owned-patch-size-supported",patch->size<=30))return false;
    if(!o.Leaf("owned-patch-size-in-recipe",patch->size<=size))return false;
    if(!o.Leaf("owned-patch-original-bytes",std::memcmp(patch->code.data()+32,bytes,patch->size)==0))return false;
    if(!o.Leaf("owned-patch-PatchIntact",detail::PatchIntact(*patch)))return false;
    o.spanOffset=patch->size;
    return detail::Equal(live+patch->size,bytes+patch->size,size-patch->size,o);
}
