inline bool StateSwapObservedDirectFields(const void* object,const StateSwapProfile& profile)noexcept {
    const auto& f=profile.fields;
    const auto context=reinterpret_cast<uintptr_t>(object);if(context<f.context)return false;
    const auto b=context-f.context;if(b>UINTPTR_MAX-(f.directFlag+1))return false;
    const auto read8=[](uintptr_t p,unsigned char& v)noexcept{return detail::Memory(reinterpret_cast<const void*>(p),&v,1);};
    const auto readPtr=[](uintptr_t p,uintptr_t& v)noexcept{return detail::Memory(reinterpret_cast<const void*>(p),&v,sizeof(v));};
    unsigned char select0=0xff,select1=0xff,flag=0xff,mode=0xff,stateMode=0xff,stateFlag=0xff;
    uint32_t deferred=UINT32_MAX;uintptr_t current=0,initial=0,stateData=0,pending=0,statePending=0;
    if(!read8(b+f.select0,select0) || select0!=1 || !read8(b+f.select1,select1) || select1!=1 ||
        !detail::Memory(reinterpret_cast<const void*>(b+f.deferred),&deferred,sizeof(deferred)) || deferred!=0 ||
        !read8(b+f.directFlag,flag) || flag!=0 ||
        !readPtr(b+f.current,current) || !current || current>UINTPTR_MAX-(f.stateData+sizeof(uintptr_t)) ||
        !readPtr(b+f.initial,initial) || current==initial ||
        !read8(current+f.stateFlag,stateFlag) || stateFlag!=0 ||
        !readPtr(current+f.stateData,stateData) || !stateData || stateData>UINTPTR_MAX-0x5a7f ||
        !readPtr(stateData+0x5a70,statePending) || statePending!=0 ||
        !readPtr(b+f.pending,pending) || pending!=0 ||
        !read8(b+f.mode,mode) || !read8(stateData+0x5a7e,stateMode) || mode!=stateMode)return false;
    return true;
}
inline bool StateSwapObservedForwardTargetsLocked(const void* object,const void* table,std::array<void*,6>& targets)noexcept {
    // Returns fixed canonical ENTRY addresses, never trampolines or observed targets.
    // Consumer must still require its expected hooked target + Required/PatchIntact.
    // Guard, StableLocked, alias identity and lifetime/race gates remain caller-owned.
    targets.fill(nullptr);
    if(!StateSwapObservedTableLocked(object,table,132))return false;
    const auto& image=detail::Ledger().images[0];
    const auto* profile=SelectStateSwapProfile(image);
    if(!profile || !StateSwapObservedDirectFields(object,*profile) ||
       !StateSwapObservedForwardCodeIntact(image,*profile))return false;
    constexpr std::array<unsigned,6> slots={27,28,58,110,114,131};
    const auto base=reinterpret_cast<uintptr_t>(image.live);
    std::array<void*,6> exact{};
    for(unsigned n=0;n<slots.size();++n){
        const auto rva=(*profile->source)[slots[n]];
        if(base>UINTPTR_MAX-rva)return false;
        exact[n]=reinterpret_cast<void*>(base+rva);
        if(!detail::Executable(exact[n]))return false;
    }
    if(!StateSwapObservedDirectFields(object,*profile))return false;
    targets=exact;return true;
}
