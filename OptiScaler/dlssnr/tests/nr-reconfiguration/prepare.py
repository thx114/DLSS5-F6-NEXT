"""Extract the live NR retirement implementation. This script never compiles.

Default: validate extraction only. --emit writes production.inc beside this file;
--check requires that an existing production.inc matches the current sources.
No runner, product source, build output, or user configuration is modified.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
LATE = ROOT / "OptiScaler/shaders/dlssnr/DlssNr_Late.inl"
LIFETIME = LATE.with_name("DlssNr_RecordingLifetime.h")
ORDERED = LATE.with_name("DlssNr_OrderedLifetime.h")

# Skip comments and quoted literals when locating the closing brace. Source
# comments/log strings must not silently truncate the implementation under test.
TOKENS = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[{}]', re.S)


def extract(text: str, signature: str) -> str:
    matches = list(re.finditer(r"(?m)^\s*" + re.escape(signature), text))
    if len(matches) != 1:
        raise ValueError(f"expected one production definition of {signature!r}, found {len(matches)}")
    start = matches[0].start()
    start += len(text[start:]) - len(text[start:].lstrip())
    depth = 0
    for token in TOKENS.finditer(text, start):
        if token.group() == "{":
            depth += 1
        elif token.group() == "}":
            depth -= 1
            if depth == 0:
                return text[start:token.end()]
    raise ValueError(f"unterminated production definition: {signature}")


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError(f"negative control requires one exact production operand: {old!r}")
    return text.replace(old, new, 1)


def render() -> str:
    raw = {path: path.read_bytes() for path in (LATE, LIFETIME, ORDERED)}
    late, lifetime, ordered = (raw[path].decode("utf-8-sig").replace("\r\n", "\n") for path in raw)
    helper = extract(late, "void RetireCompletedPrivateRecordings(")
    # Mutation controls run the same scenario assertions. They must fail when a
    # genuine GPU gate, idle-only gate, or failed-Reset retention is removed.
    controls = []
    for name, old, new in (
        ("IgnoreGpuCompletion", "!use->GpuComplete()", "false"),
        ("IgnorePending", "slot.pending ||", "false ||"),
        ("IgnoreResetFailure", '                continue;\n            }\n            FinishedPictureResetCommandList(identity);',
         '                /* negative control: wrongly fall through */\n            }\n            FinishedPictureResetCommandList(identity);'),
    ):
        mutated = replace_once(helper, old, new)
        controls.append(replace_once(mutated, "void RetireCompletedPrivateRecordings(", f"void {name}("))
    hashes = "\n".join(f"// {path.relative_to(ROOT).as_posix()} SHA256 {hashlib.sha256(data).hexdigest()}"
                       for path, data in raw.items())
    methods = "\n".join(extract(lifetime, signature) for signature in (
        "bool Watches(ID3D12CommandList* list) const",
        "void ResetRecording(ID3D12CommandList* list)",
        "void Collect()",
        "Uses Snapshot()",
    ))
    return f"""// GENERATED by prepare.py --emit; regenerate after any production edit.
// Actual production bodies below are not reimplemented by the fixture.
{hashes}
namespace DlssNrGpuLifetime {{
{extract(lifetime, 'struct Token')};
using Use = std::shared_ptr<Token>;
using Uses = std::vector<Use>;
{extract(lifetime, 'inline bool Complete(const Uses& uses)')}

// Host boundary only: synthetic device identities; no D3D/COM device query.
inline bool SameDevice(ID3D12CommandList* list, ID3D12CommandAllocator* allocator)
{{ return list && allocator && list->device == allocator->device; }}

class Registry {{
    std::unordered_map<ID3D12CommandList*, Use> open_;
    Uses outstanding_;
    bool halted_ = false;
public:
    // Fixture setup replaces Recording/Submitted only. Closure, polling, owner
    // retirement and shared snapshot collection below are the production code.
    void Seed(ID3D12CommandList* list, const Use& use)
    {{ open_[list] = use; outstanding_.push_back(use); }}
    void TrackOldGeneration(const Use& use) {{ outstanding_.push_back(use); }}
    void Clear() {{ open_.clear(); outstanding_.clear(); halted_ = false; }}
{methods}
}};
{extract(ordered, 'template <class Entries, class Release> void CollectRetired(')}
}} // namespace DlssNrGpuLifetime

// Fixture integration declarations; TickNrRetired uses the actual collector.
DlssNrGpuLifetime::Registry g_nrGpuWork;
void TickNrRetired();
namespace Late {{
{extract(late, 'bool Finished(const Slot& slot)')}
{helper}
// Deliberately unsafe TEST-ONLY copies for assertion sensitivity checks.
{chr(10).join(controls)}
}} // namespace Late
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--emit", action="store_true")
    modes.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # A tiny lexical self-check also exercises misleading braces in strings and
    # comments, rather than relying on the current production formatting alone.
    probe = 'void Probe() { /* } */ const char* s = "}"; if (s) { } }\nvoid Next() {}'
    assert extract(probe, "void Probe()") == probe.split("\n")[0]
    expected = render()
    destination = HERE / "production.inc"
    if args.emit:
        if destination.exists() and not destination.read_text(encoding="utf-8").startswith("// GENERATED by prepare.py"):
            raise ValueError("refusing to overwrite a non-generated test file")
        destination.write_text(expected, encoding="utf-8", newline="\n")
    elif args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != expected:
            raise ValueError("production.inc is absent or stale; run prepare.py --emit")
    print(f"PASS live production extraction{' and freshness' if args.check else ''}; no compiler or CPU fixture executed")


if __name__ == "__main__":
    main()
