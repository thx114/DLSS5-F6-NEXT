#requires -Version 7.0
[CmdletBinding()]
param(
    [string]$Dxc = (Join-Path $PSScriptRoot '../shader_tools/dxc.exe'),
    [switch]$CheckOnly
)

# Lead owns invocation. This file performs no work merely by being checked in.
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false
$utf8 = [Text.UTF8Encoding]::new($false)
$sourcePath = Join-Path $PSScriptRoot 'precompiled/RF.hlsl'
$headerPath = Join-Path $PSScriptRoot 'precompiled/RF_Shader.h'
$csoPath = Join-Path $PSScriptRoot 'precompiled/RF_Shader.cso'
$source = [IO.File]::ReadAllText($sourcePath).Replace("`r`n", "`n")
$common = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'RF_Common.h')).Replace("`r`n", "`n")
$match = [regex]::Match($common, '(?s)inline constexpr char rfSource\[\] = R"rf\((.*?)\)rf";')
if (!$match.Success -or $match.Groups[1].Value -cne $source) {
    throw 'RF_Common.h rfSource and precompiled/RF.hlsl must match exactly (LF normalized).'
}
if ($source -notmatch '\[numthreads\(16, 16, 1\)\]') { throw 'Update RFThreadsX/Y with shader group size.' }
[uint64]$hash = 2166136261
foreach ($item in $utf8.GetBytes($source)) {
    $hash = (($hash -bxor [uint64]$item) * [uint64]16777619) -band [uint64]4294967295
}
$hashLiteral = '0x{0:X8}u' -f $hash

if ($CheckOnly) {
    $header = [IO.File]::ReadAllText($headerPath)
    if (!$header.Contains("#define RF_SOURCE_FNV1A $hashLiteral")) { throw 'Stale RF shader header fingerprint.' }
    $array = [regex]::Match($header, '(?s)RF_cso\[\] = \{(.*?)\};')
    if (!$array.Success) { throw 'Missing RF_cso array.' }
    [byte[]]$embedded = @([regex]::Matches($array.Groups[1].Value, '0x([0-9A-Fa-f]{2})') |
        ForEach-Object { [Convert]::ToByte($_.Groups[1].Value, 16) })
    $binary = [IO.File]::ReadAllBytes($csoPath)
    if ([Convert]::ToBase64String($embedded) -cne [Convert]::ToBase64String($binary)) {
        throw 'RF_Shader.h and RF_Shader.cso differ.'
    }
    Write-Output "RF source/header/CSO consistency: $hashLiteral"
    return
}

$temporary = Join-Path $PSScriptRoot ('precompiled/.rf-' + [Guid]::NewGuid().ToString('N') + '.cso')
try {
    & $Dxc -T cs_6_0 -E CSMain -O3 -Ges -WX -Fo $temporary $sourcePath
    if ($LASTEXITCODE -ne 0) { throw "RF DXC failed: $LASTEXITCODE" }
    $binary = [IO.File]::ReadAllBytes($temporary)
    if ($binary.Length -eq 0) { throw 'DXC emitted empty RF bytecode.' }
    $text = [Text.StringBuilder]::new()
    $null = $text.Append("#pragma once`n`n// Generated by Generate-RFShader.ps1; do not edit.`n")
    $null = $text.Append("#define RF_SOURCE_FNV1A $hashLiteral`n`ninline constexpr unsigned char RF_cso[] = {`n")
    for ($index = 0; $index -lt $binary.Length; $index += 16) {
        $end = [Math]::Min($index + 15, $binary.Length - 1)
        $items = @($binary[$index..$end] | ForEach-Object { '0x{0:X2}' -f $_ })
        $null = $text.Append('    ' + ($items -join ', ') + ",`n")
    }
    $null = $text.Append("};`n")
    [IO.File]::WriteAllBytes($csoPath, $binary)
    [IO.File]::WriteAllText($headerPath, $text.ToString(), $utf8)
    Write-Output "Generated RF_Shader.h and RF_Shader.cso ($($binary.Length) bytes, $hashLiteral)."
} finally {
    if (Test-Path -LiteralPath $temporary) { Remove-Item -LiteralPath $temporary }
}
